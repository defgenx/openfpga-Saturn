#!/usr/bin/env python3
# mc_gen.py <core_constraints.sdc> <VDP2P.sv> <out.svh>: MC_CHECK monitor for the VDP2 multicycle set of the SDC
# (vdp2_ce_r). Every listed register must change only at a CE_R edge (CE_R high in the clock that ends there).
# Block-local variables (declared inside an always block) have no hierarchical name and are skipped (listed).
import re, sys

sdc, rtl, out = sys.argv[1:4]
names = re.search(r'set vdp2_ce_r \{(.*?)\}', open(sdc).read(), re.S).group(1).split()
src = open(rtl).read()
# unpacked typedefs of the package and the elements that are registers
RB = ['.RxPN', '.RxCH', '.RxCT', '.RxCRCT', '.RxCTTP', '.RxOVR'] + \
     ['.%s[%d]' % (f, i) for f in ('RxPNS', 'RxCHS', 'RxCELLX', 'RxCTS', 'RxCT_EN') for i in range(2)]
TYPED = {'NxPNCNT_t': ['[0]', '[1]'], 'NxCHCNT_t': ['[0]', '[1]', '[2]', '[3]'],
         'VRAMAccessPipeline_t': ['[1].AxNA', '[1].BxNA'], 'NBGPipeline_t': ['[1].NxPN_EN[%d]' % i for i in range(4)],
         'RBGPipeline_t': ['[%d]%s' % (j, f) for j in range(2) for f in RB],
         'PNPipe_t': ['[%d][%d]' % (j, i) for j in range(2) for i in range(8)],
         'RPNPipe_t': ['[%d][%d]' % (j, i) for j in range(2) for i in range(2)]}
mod_decl = {}
for m in re.finditer(r'^\t(?:bit|reg|logic|wire|[A-Za-z_]\w*_t)\b(.*?);', src, re.M):
	ty = m.group(0).split()[0]
	body = re.sub(r'^\s*\[[^\]]*\]\s*', '', m.group(1).strip())   # packed range after bit/reg
	if '=' in body:   # continuous assignment, not a variable list
		continue
	for part in body.split(','):
		pm = re.match(r'\s*(\w+)\s*((?:\[\s*\d+\s*\])*)', part)
		if pm:
			dims = [int(d) for d in re.findall(r'\[\s*(\d+)\s*\]', pm.group(2))]
			mod_decl.setdefault(pm.group(1), (ty, dims))
for m in re.finditer(r"^\toutput\b[^\n]*?(\w+)\s*,?\s*$", src, re.M):   # output ports written by always blocks
	mod_decl.setdefault(m.group(1), ('reg', []))

def elems(name, dims):
	if not dims:
		return ['']
	return ['[%d]%s' % (i, r) for i in range(dims[0]) for r in elems(name, dims[1:])]

sig, skipped = [], []
for n in names:
	base = n.split('.')[0]
	if base not in mod_decl:
		skipped.append(n)
		continue
	ty, dims = mod_decl[base]
	if '.' in n:
		sig.append('u_dut.' + n)
	elif dims:
		sig += ['u_dut.%s%s' % (n, e) for e in elems(n, dims)]
	elif ty in TYPED:
		sig += ['u_dut.%s%s' % (n, e) for e in TYPED[ty]]
	else:
		sig.append('u_dut.' + n)
for t in ('tap2', 'tap3', 'tap4', 'whit8', 'whit33', 'lcsd_tap'):
	sig.append('u_dut.%s.wp' % t)
# single-cycle control set (every-clock or CE_F registers); it must show changes outside CE_R edges
ctl = ['u_dut.CSEQ', 'u_dut.CPN', 'u_dut.USL', 'u_dut.HA[0]', 'u_dut.REGS.SCXIN0', 'u_dut.A']

with open(out, 'w') as f:
	f.write('// generated by mc_gen.py from %s; skipped (block-local): %s\n' % (sdc.split('/')[-1], ' '.join(skipped)))
	f.write('\tlocalparam int MC_N = %d;\n\tinteger mc_chg[MC_N], mc_viol[MC_N];\n\tinteger ctl_chg = 0, ctl_viol = 0;\n' % len(sig))
	f.write('\treg mc_ce = 0, mc_res = 0;\n\talways @(posedge CLK) begin mc_ce <= CE_R; mc_res <= RST_N & RES_N; end\n')
	f.write('\tinitial for (int i = 0; i < MC_N; i++) begin mc_chg[i] = 0; mc_viol[i] = 0; end\n')
	for i, s in enumerate(sig):
		f.write('\treg [$bits(%s)-1:0] mc_q%d;\n' % (s, i))
		f.write('\talways @(negedge CLK) begin if (mc_res && %s != mc_q%d) begin mc_chg[%d] = mc_chg[%d] + 1; '
		        'if (!mc_ce) mc_viol[%d] = mc_viol[%d] + 1; end mc_q%d <= %s; end\n' % (s, i, i, i, i, i, i, s))
	f.write('\treg [%s-1:0] mc_cq;\n' % '+'.join('$bits(%s)' % c for c in ctl))
	f.write('\talways @(negedge CLK) begin if (mc_res && {%s} != mc_cq) begin ctl_chg = ctl_chg + 1; '
	        'if (!mc_ce) ctl_viol = ctl_viol + 1; end mc_cq <= {%s}; end\n' % (', '.join(ctl), ', '.join(ctl)))
	f.write('\tfinal begin\n\t\tinteger tv, tc; tv = 0; tc = 0;\n')
	for i, s in enumerate(sig):
		f.write('\t\ttc += mc_chg[%d]; tv += mc_viol[%d]; if (mc_viol[%d] != 0 || mc_chg[%d] == 0) '
		        '$display("MC_CHECK %s changes=%%0d off_ce_r=%%0d", mc_chg[%d], mc_viol[%d]);\n' % (i, i, i, i, s, i, i))
	f.write('\t\t$display("MC_CHECK signals=%0d changes=%0d off_ce_r=%0d control_changes=%0d control_off_ce_r=%0d", '
	        'MC_N, tc, tv, ctl_chg, ctl_viol);\n\tend\n')
