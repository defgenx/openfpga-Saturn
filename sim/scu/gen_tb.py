# Generates tb_scu.sv / tb_dsp.sv (golden REF_* vs module under test on identical inputs) and name tables.
import sys
DUT = sys.argv[1] if len(sys.argv) > 1 else "SCU"
OUT = sys.argv[2] + "/" if len(sys.argv) > 2 else ""
rng = lambda w: "" if w == 1 else "[%d:0] " % (w - 1)

scu_ins = [("CE_R",1),("CE_F",1),("RES_N",1),("CA",25),("CDI",32),("CCS1_N",1),("CCS2_N",1),("CCS3_N",1),
       ("CRD_WR_N",1),("CDQM_N",4),("CRD_N",1),("CIVECF_N",1),("CBACK_N",1),("ECDI",32),("ECWAIT_N",1),
       ("ADI",16),("AWAIT_N",1),("AIRQ_N",1),("BDI",16),("BRDY1_N",1),("IRQ1_N",1),("BRDY2_N",1),
       ("IRQV_N",1),("IRQH_N",1),("IRQL_N",1),("BRDYS_N",1),("IRQS_N",1),("MIREQ_N",1),("FAST",1)]
scu_outs = [("CDO",32),("CWAIT_N",1),("CIRL_N",4),("CBREQ_N",1),("ECA",25),("ECDO",32),("ECDQM_N",4),
        ("ECRD_WR_N",1),("ECCS3_N",1),("ECRD_N",1),("ECBURST",1),("ECRFS",1),("AA",26),("ADO",16),
        ("AFC",2),("AAS_N",1),("ACS0_N",1),("ACS1_N",1),("ACS2_N",1),("ARD_N",1),("AWRL_N",1),
        ("AWRU_N",1),("ATIM0_N",1),("ATIM1_N",1),("ATIM2_N",1),("BDO",16),("BADDT_N",1),("BDTEN_N",1),
        ("BREQ_N",1),("BCS1_N",1),("BCS2_N",1),("BCSS_N",1)]
dsp_ins = [("CE",1),("RES_N",1),("CE_R",1),("CE_F",1),("A",2),("DI",32),("WE",4),("RE",1),("DMA_DI",32),
           ("DMA_ACK",1),("DMA_END",1)]
dsp_outs = [("DO",32),("DSO",32),("RA0W",1),("WA0W",1),("DMAW",1),("DMA_DO",32),("DMA_WE",1),("DMA_REQ",1),
            ("DMA_RUN",1),("DMA_LAST",1),("IRQ",1),("DBG_DECI",78),("DBG_Q",48),("DBG_AC",48),("DBG_P",48),
            ("HOOK1",1),("HOOK2",1)]

def gen(top, ref, dut, params, ins, outs, extra=""):
    s = ["// Differential wrapper: golden %s and %s on identical inputs.\n"
         "// Generated by gen_tb.py; do not edit.\n" % (ref, dut)]
    s.append("module %s %s (\n\tinput CLK,\n\tinput RST_N" % (top, params[0]))
    for n, w in ins: s.append(",\n\tinput %s%s" % (rng(w), n))
    for n, w in outs: s.append(",\n\toutput %s%s" % (rng(w), n))
    s.append(",\n\toutput [%d:0] MM\n);\n" % (len(outs) - 1))
    s.append(extra)
    for n, w in outs:
        s.append("\twire %sR_%s;\n\twire %sD_%s;\n" % (rng(w), n, rng(w), n))
    for mod, tag, nm in ((ref, "R", "ref_i"), (dut, "D", "dut_i")):
        t = "\t%s %s %s (\n\t\t.CLK(CLK), .RST_N(RST_N)" % (mod, params[1], nm)
        for n, w in ins: t += ",\n\t\t.%s(%s)" % (n, n)
        for n, w in outs: t += ",\n\t\t.%s(%s_%s)" % (n, tag, n)
        s.append(t + "\n\t);\n")
    for i, (n, w) in enumerate(outs):
        if n == "DSO" and DUT != "SCU" and DUT != "SCUP":
            s.append("\tassign MM[%d] = (R_RA0W | R_WA0W) && (R_DSO[24:0] !== D_DSO[24:0]);\n" % i)   # DSO is only used with RA0W/WA0W; the DMA control bits have their own port
        else:
            s.append("\tassign MM[%d] = R_%s !== D_%s;\n" % (i, n, n))
    for n, w in outs: s.append("\tassign %s = R_%s;\n" % (n, n))
    s.append("endmodule\n")
    open(OUT + top + ".sv", "w").write("".join(s))
    open(OUT + top + "_names.h", "w").write("// Generated by gen_tb.py\n#pragma once\nstatic const char* OUT_NAMES[] = {"
                                  + ",".join('"%s"' % n for n, w in outs) + "};\n")

gen("tb_scu", "REF_SCU", DUT, ("#(parameter RAMH_SLOW=0)", "#(RAMH_SLOW)"), scu_ins, scu_outs)
if DUT == "SCUP2":   # no debug taps in SCUP2_DSP
    dsp_outs = [o for o in dsp_outs if not o[0].startswith("DBG_") and not o[0].startswith("HOOK")]
gen("tb_dsp", "REF_SCU_DSP", DUT + "_DSP", ("", ""), dsp_ins, dsp_outs,
    "\tinitial if ($bits(SCUDSP_PKG::DecInst_t) != 78) $fatal(1, \"DecInst_t width\");\n" if DUT == "SCU" else "")
