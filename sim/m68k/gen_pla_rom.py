#!/usr/bin/env python3
"""Factor the FX68K opcode->microcode-entry PLA (uaddrDecode) into three small ROMs and emit m68kp_plarom.sv.
 L1: opcode[15:6]                -> column id (1 of ~100 distinct columns over the EA field)
 L2: {column id, EA class}       -> entry-triple id + illegal flag
 L3: entry-triple id             -> a1, a2, a3
 4E40-4E7F (hi 0x139) depends on all six low bits: it uses a 64-entry side table (L2S) instead of L2.
Input: pla/pla_table.txt from `make pla`  (opcode a1 a2 a3 flags per line; flags bit2 = illegal).
Verifies the reconstruction for all 65536 opcodes before writing."""
import sys
tab = [l.split() for l in open(sys.argv[1])]
out = sys.argv[2]
V = [(int(t[1], 16), int(t[2], 16), int(t[3], 16), int(t[4], 16) >> 2 & 1) for t in tab]   # a1 a2 a3 illegal
SPECIAL_HI = 0x139

def ea_class(lo):
    m, r = lo >> 3, lo & 7
    if lo == 0: return 13
    if m == 7: return {0: 7, 1: 8, 2: 9, 3: 10, 4: 11}.get(r, 12)
    return m
# class representatives: any lo6 of the class (all members must agree, verified below)
rep = {}
for lo in range(64): rep.setdefault(ea_class(lo), lo)

cols = {}; l1 = [0] * 1024
for hi in range(1024):
    if hi == SPECIAL_HI: continue
    col = tuple(V[hi * 64 + rep[c]] for c in range(14))
    l1[hi] = cols.setdefault(col, len(cols))
SPEC = len(cols)                      # column id of the special row
l1[SPECIAL_HI] = SPEC
trip = {}
def tid(v): return trip.setdefault(v[:3], len(trip))
l2 = {}                               # (col, class) -> (tid, ill)
for col, cid in cols.items():
    for c in range(14): l2[(cid, c)] = (tid(col[c]), col[c][3])
l2s = [(tid(V[SPECIAL_HI * 64 + lo]), V[SPECIAL_HI * 64 + lo][3]) for lo in range(64)]
# verify
ncol = SPEC + 1
l3 = [None] * len(trip)
for k, i in trip.items(): l3[i] = k
bad = 0
for op in range(65536):
    hi, lo = op >> 6, op & 63
    cid = l1[hi]
    t, ill = l2s[lo] if cid == SPEC else l2[(cid, ea_class(lo))]
    if l3[t] + (ill,) != V[op]: bad += 1
if bad: sys.exit("reconstruction mismatch: %d opcodes" % bad)
nt = len(trip)
print("columns %d, triples %d, L2 entries %d" % (ncol, nt, len(l2)), file=sys.stderr)
cb = max(1, (ncol - 1).bit_length()); tb = max(1, (nt - 1).bit_length())
assert ncol <= 128 and nt <= 512
with open(out, 'w') as o:
    o.write("// Generated by sim/m68k/gen_pla_rom.py from the FX68K PLA; do not edit.\n")
    o.write("// ROM-based replacement of uaddrDecode: opcode -> microcode entry addresses a1/a2/a3, three clk latency.\n\n")
    o.write("module mp_uaddrRom(input clk, input [15:0] opcode, output [9:0] a1, a2, a3, output isIllegal, isPrivSpecial);\n")
    o.write("\twire [3:0] eaClass; wire isSpecial;\n")
    o.write("\t// EA class: 0-6 modes, 7 abs.w, 8 abs.l, 9 (d16,PC), 10 (d8,PC,Xn), 11 #imm, 12 invalid, 13 low six bits zero\n")
    o.write("\tassign eaClass = (opcode[5:0] == 6'd0) ? 4'd13 : (opcode[5:3] != 3'd7) ? {1'b0, opcode[5:3]} :\n")
    o.write("\t\t(opcode[2:0] == 3'd0) ? 4'd7 : (opcode[2:0] == 3'd1) ? 4'd8 : (opcode[2:0] == 3'd2) ? 4'd9 :\n\t\t(opcode[2:0] == 3'd3) ? 4'd10 : (opcode[2:0] == 3'd4) ? 4'd11 : 4'd12;\n")
    o.write("\t(* ramstyle = \"M10K\", rom_style = \"M10K\" *) reg [%d:0] rom1 [0:1023];\n" % (cb - 1))
    o.write("\t(* ramstyle = \"M10K\", rom_style = \"M10K\" *) reg [%d:0] rom2 [0:2047];\n" % tb)
    o.write("\t(* ramstyle = \"M10K\", rom_style = \"M10K\" *) reg [29:0] rom3 [0:%d];\n" % (nt - 1 if nt > 256 else 255))
    o.write("\treg [%d:0] colId; reg [%d:0] q2; reg [29:0] r3; reg [3:0] eaq;\n" % (cb - 1, tb))
    o.write("\tinitial begin\n")
    for i, v in enumerate(l1): o.write("\t\trom1[%d] = %d'd%d;\n" % (i, cb, v))
    for (cid, c), (t, ill) in sorted(l2.items()): o.write("\t\trom2[%d] = %d'h%x;\n" % (cid * 16 + c, tb + 1, ill << tb | t))
    for i in range(cb and len(l2s)): pass
    o.write("\tend\n")
    # side table in a case statement (64 entries)
    o.write("\treg [%d:0] side;\n\talways_comb case (opcode[5:0])\n" % tb)
    for lo, (t, ill) in enumerate(l2s): o.write("\t\t6'd%d: side = %d'h%x;\n" % (lo, tb + 1, ill << tb | t))
    o.write("\tendcase\n")
    o.write("\tinitial begin\n")
    for i, k in enumerate(l3): o.write("\t\trom3[%d] = {10'h%03x, 10'h%03x, 10'h%03x};\n" % (i, k[0], k[1], k[2]))
    o.write("\tend\n")
    o.write("\talways @(posedge clk) begin\n\t\tcolId <= rom1[opcode[15:6]];\n\t\teaq <= eaClass;\n")
    o.write("\t\tq2 <= rom2[{colId, eaq}];\n")
    o.write("\t\tr3 <= rom3[r2[%d:0]];\n\tend\n" % (tb - 1))
    o.write("\twire [%d:0] r2 = (colId == %d'd%d) ? side : q2;\n" % (tb, cb, SPEC))
    o.write("\tassign {a1, a2, a3} = r3;\n\tassign isIllegal = r2[%d];\nendmodule\n" % tb)
